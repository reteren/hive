import { writeFileSync } from "node:fs";
const OUT = "C:/Users/reteren/AppData/Local/Temp/claude";
const page = (await fetch(`http://localhost:9334/json/list`).then((r) => r.json())).find((t) => t.type === "page" && t.url.includes("1450"));
const ws = new WebSocket(page.webSocketDebuggerUrl); let id = 0; const pending = new Map(); const errors = [];
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.method === "Runtime.exceptionThrown") errors.push(m.params.exceptionDetails.exception?.description?.slice(0, 220)); if (pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } };
await new Promise((r) => (ws.onopen = r));
const send = (method, params = {}) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params })); });
await send("Runtime.enable");
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const ev = async (expression) => { const r = await send("Runtime.evaluate", { expression, awaitPromise: true, returnByValue: true }); return r.result?.result?.value ?? r.result?.exceptionDetails?.exception?.description; };
const mouse = (type, x, y) => send("Input.dispatchMouseEvent", { type, x, y, button: type === "mouseMoved" ? "none" : "left", buttons: type === "mousePressed" ? 1 : 0, clickCount: type === "mouseMoved" ? 0 : 1 });
const click = async (x, y) => { await mouse("mouseMoved", x, y); await mouse("mousePressed", x, y); await mouse("mouseReleased", x, y); await wait(300); };
const key = async (k, code, vk, modifiers = 0) => { await send("Input.dispatchKeyEvent", { type: "keyDown", key: k, code, windowsVirtualKeyCode: vk, modifiers }); await send("Input.dispatchKeyEvent", { type: "keyUp", key: k, code, windowsVirtualKeyCode: vk, modifiers }); await wait(250); };
const shot = async (n) => writeFileSync(`${OUT}/${n}.png`, Buffer.from((await send("Page.captureScreenshot", { format: "png" })).result.data, "base64"));
const bar = () => ev(`[...document.querySelectorAll('.left-toolbar button')].map(b=>b.getAttribute('aria-label')+(b.getAttribute('aria-pressed')==='true'?'*':'')).join(' | ')`);
const state = () => ev(`(async()=>{const t=await import('/src/tools/tool.svelte.ts');const d=await import('/src/drawing/tools.svelte.ts');return t.tool.active+' / '+d.drawingTools.active})()`);
const center = (sel) => ev(`(()=>{const r=document.querySelector(${JSON.stringify(sel)}).getBoundingClientRect();return [r.x+r.width/2,r.y+r.height/2]})()`);
await send("Page.reload"); await wait(2500);
await mouse("mouseMoved", 600, 400);
console.log("0 bar:", await bar());
await key("c", "KeyC", 67);
console.log("1 C:", await state(), "|", await bar());
await shot("d22p2-line");
const [wx, wy] = await center('.left-toolbar [aria-label^="Weak line"]');
await click(wx, wy);
console.log("1 click weak:", await state());
await key("c", "KeyC", 67); console.log("1 C again:", await state());
const [lx, ly] = await center('.left-toolbar [aria-label^="Line"]');
await click(lx, ly); console.log("1 Line button (last=weak?):", await state());
await mouse("mouseMoved", lx, ly); await wait(700);
console.log("1 line tooltip:", await ev(`document.querySelector('.tooltip-bubble')?.textContent.trim()`));
await click(lx, ly); console.log("1 Line button again:", await state());
await mouse("mouseMoved", 600, 400);
await key("d", "KeyD", 68, 2);
console.log("2 draw:", await state(), "|", await bar(), "| panel grid", await ev(`!!document.querySelector('.draw-tool-grid')`));
await wait(400); await shot("d22p2-draw");
const [fx, fy] = await center('.left-toolbar [aria-label^="Fill"]');
await click(fx, fy); console.log("2 click Fill:", await state());
await mouse("mouseMoved", fx, fy); await wait(700);
console.log("2 fill tooltip:", await ev(`document.querySelector('.tooltip-bubble')?.textContent.trim()`));
await shot("d22p2-tooltip");
await mouse("mouseMoved", 600, 400); await key("l", "KeyL", 76); console.log("2 L:", await state());
console.log("errors:", errors);
process.exit(0);
